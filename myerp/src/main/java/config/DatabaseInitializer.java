package config;

import dao.UserDAO;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

public class DatabaseInitializer {

    public static void initializeDatabase() {
        // Create an automatic safety backup of existing clinic.db before performing any operations
        backupDatabaseIfExists();

        try (Connection conn = DatabaseConfig.getConnection();
                Statement stmt = conn.createStatement()) {

            // Enable foreign-key enforcement if supported (SQLite)
            try {
                stmt.execute("PRAGMA foreign_keys = ON;");
            } catch (SQLException ignored) {
                // H2 and ANSI SQL enforce foreign keys by default
            }

            // ----------------------------------------------------------------
            // 1. Workers
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS worker (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name        TEXT NOT NULL,
                            birthDate   TEXT,
                            birthPlace  TEXT,
                            phoneNumber TEXT,
                            identityCardNumber TEXT NOT NULL,
                            function    TEXT NOT NULL,
                            famillySituation TEXT
                        );
                    """);

            // ----------------------------------------------------------------
            // 2. Payment Check
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS paymentCheck (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            workerId    INTEGER NOT NULL REFERENCES worker(id) ON DELETE CASCADE,
                            paymentDate TEXT DEFAULT CURRENT_TIMESTAMP,
                            paidAmount  REAL,
                            note        TEXT
                        );
                    """);

            // ----------------------------------------------------------------
            // 3. Bill
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS bill (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            billDate    TEXT DEFAULT CURRENT_TIMESTAMP,
                            totalCost   REAL
                        );
                    """);

            // ----------------------------------------------------------------
            // 4. Bill Item
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS billItem (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            billId      INTEGER NOT NULL REFERENCES bill(id) ON DELETE CASCADE,
                            itemName    TEXT,
                            quantity    INTEGER,
                            unitPrice   REAL
                        );
                    """);

            // ----------------------------------------------------------------
            // 5. User
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS Users (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            fullName    TEXT NOT NULL,
                            userName    TEXT NOT NULL,
                            passWord    TEXT NOT NULL,
                            userType    TEXT
                        );
                    """);

            // ----------------------------------------------------------------
            // 6. Patient
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS patient (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name        TEXT NOT NULL,
                            gender      TEXT,
                            phone       TEXT,
                            totalCost   REAL,
                            totalPaid   REAL
                        );
                    """);

            // ----------------------------------------------------------------
            // 7. TherapyPlan
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS therapyPlan (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            patientId   INTEGER REFERENCES patient(id) ON DELETE CASCADE,
                            date        TEXT DEFAULT CURRENT_TIMESTAMP,
                            cost        REAL
                        );
                    """);

            // ----------------------------------------------------------------
            // 8. Session
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS session (
                            id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            patientId       INTEGER REFERENCES patient(id) ON DELETE CASCADE,
                            therapyPlanId   INTEGER REFERENCES therapyPlan(id) ON DELETE CASCADE,
                            sessionDate     TEXT DEFAULT CURRENT_TIMESTAMP,
                            treatment       TEXT,
                            paied           TEXT,
                            cost            REAL,
                            paidAmount      REAL
                        );
                    """);

            // ----------------------------------------------------------------
            // 9. Sold
            // ----------------------------------------------------------------
            stmt.execute("""
                        CREATE TABLE IF NOT EXISTS sold (
                            id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            itemName    TEXT,
                            soldDate    TEXT DEFAULT CURRENT_TIMESTAMP,
                            soldPrice   REAL,
                            quantity    REAL
                        );
                    """);

            // Widen string column types in existing tables to TEXT to prevent truncation
            alterColumnToText(stmt, "worker", "name");
            alterColumnToText(stmt, "billItem", "itemName");
            alterColumnToText(stmt, "patient", "name");
            alterColumnToText(stmt, "patient", "gender");
            alterColumnToText(stmt, "patient", "phone");
            alterColumnToText(stmt, "session", "paied");
            alterColumnToText(stmt, "sold", "itemName");

            // Normalize existing user records without a defined role to 'Admin'
            stmt.execute("UPDATE Users SET userType = 'Admin' WHERE userType IS NULL OR TRIM(userType) = '';");

            // ----------------------------------------------------------------
            // 10. Check and execute legacy SQLite -> H2 migration if needed
            // ----------------------------------------------------------------
            String legacyDbPath = System.getProperty("user.home") + "/clinic/clinic.db";
            if (DatabaseMigrator.shouldMigrate(legacyDbPath)) {
                DatabaseMigrator.migrate(legacyDbPath, conn);
            }

            // Seed a default admin user if none exists yet
            UserDAO.seedDefaultAdmin();

            // Create performance indexes to ensure instant queries over LAN
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_session_date ON session(sessionDate);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_session_patientId ON session(patientId);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_session_therapyPlanId ON session(therapyPlanId);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_therapyplan_patientId ON therapyPlan(patientId);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_bill_date ON bill(billDate);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_billitem_billId ON billItem(billId);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_paymentcheck_workerId ON paymentCheck(workerId);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_sold_date ON sold(soldDate);");
            stmt.execute("CREATE INDEX IF NOT EXISTS idx_patient_name ON patient(name);");

            // Ensure patient totalCost and totalPaid are accurate from all sessions & therapy plans
            try {
                stmt.execute("""
                    UPDATE patient p
                    SET totalCost = COALESCE((SELECT SUM(cost) FROM session s WHERE s.patientId = p.id AND s.therapyPlanId IS NULL), 0) +
                                    COALESCE((SELECT SUM(cost) FROM therapyPlan tp WHERE tp.patientId = p.id), 0),
                        totalPaid = COALESCE((SELECT SUM(paidAmount) FROM session s WHERE s.patientId = p.id AND s.therapyPlanId IS NULL), 0) +
                                    COALESCE((SELECT SUM(cost) FROM therapyPlan tp WHERE tp.patientId = p.id), 0);
                """);
            } catch (SQLException ignored) {
                // Table might be empty on fresh first boot
            }

            System.out.println("Database initialized successfully.");

        } catch (SQLException e) {
            System.err.println("❌ Database initialization failed: " + e.getMessage());
            throw new RuntimeException("Database initialization failed", e);
        }
    }

    /**
     * Creates a timestamped backup copy of clinic.db in ~/clinic/backups/
     * before running any schema or database operations.
     */
    private static void backupDatabaseIfExists() {
        try {
            java.nio.file.Path dbPath = java.nio.file.Paths.get(DatabaseConfig.getDatabasePath());
            if (java.nio.file.Files.exists(dbPath) && java.nio.file.Files.size(dbPath) > 0) {
                java.nio.file.Path backupDir = dbPath.getParent().resolve("backups");
                java.nio.file.Files.createDirectories(backupDir);
                String timestamp = java.time.LocalDateTime.now()
                        .format(java.time.format.DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss"));
                java.nio.file.Path backupFile = backupDir.resolve("clinic_backup_" + timestamp + ".db");
                java.nio.file.Files.copy(dbPath, backupFile, java.nio.file.StandardCopyOption.REPLACE_EXISTING);
                System.out.println("✅ Pre-launch database backup created: " + backupFile);
            }
        } catch (Exception e) {
            System.err.println("⚠️ Warning: Failed to create database backup: " + e.getMessage());
        }
    }

    private static void alterColumnToText(Statement stmt, String table, String column) {
        try {
            stmt.execute("ALTER TABLE " + table + " ALTER COLUMN " + column + " SET DATA TYPE TEXT;");
        } catch (SQLException ignored) {
            // Ignore if column is already TEXT or table is not yet created
        }
    }
}
